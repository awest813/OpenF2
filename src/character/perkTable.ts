function fromRaw(r: number[]): PerkDescription {
    return {
        frmId: r[0], maxRank: r[1], minLevel: r[2], stat: r[3], statModifier: r[4],
        param1: r[5], value1: r[6], paramMode: r[7], param2: r[8], value2: r[9], stats: r.slice(10, 17),
    }
}

export const PERK_COUNT = RAW.length

/** The live table (sfall set_perk_* edits it). */
export const PERK_DESCRIPTIONS: PerkDescription[] = RAW.map(fromRaw)

/** Script-set names and descriptions (set_perk_name / set_perk_desc). */
export const perkNameOverrides = new Map<number, string>()
export const perkDescOverrides = new Map<number, string>()

/** Put the table back as the engine ships it (a new game or a load). */
export function resetPerkDescriptions(): void {
    RAW.forEach((r, i) => { PERK_DESCRIPTIONS[i] = fromRaw(r) })
    perkNameOverrides.clear()
    perkDescOverrides.clear()
}

export interface PerkCanAddSubject {
    /** The critter is the player (only the player's level is checked). */
    isPlayer: boolean
    level: number
    rank: number
    stat(index: number): number
    skill(index: number): number
    gvar(index: number): number
}

const GVAR_BIT = 0x4000000

function requirementMet(s: PerkCanAddSubject, param: number, value: number): boolean {
    const isVariable = (param & GVAR_BIT) !== 0
    const index = param & ~GVAR_BIT
    const have = isVariable ? s.gvar(index) : s.skill(index)
    if (value < 0) {return isVariable ? have < value : have < -value}
    return have >= value
}

/** perk.cc perkCanAdd. `levelMod` is sfall's set_perk_level_mod. */
export function perkCanAdd(s: PerkCanAddSubject, perk: number, levelMod = 0): boolean {
    const d = PERK_DESCRIPTIONS[perk]
    if (!d || d.maxRank === -1) {return false}
    if (s.rank >= d.maxRank) {return false}
    if (s.isPlayer && s.level + levelMod < d.minLevel) {return false}

    const req1 = d.param1 === -1 || requirementMet(s, d.param1, d.value1)
    if (!req1 || d.paramMode === 2) {
        if (d.paramMode === 0) {return false}
        if (!req1 && d.paramMode === 2) {return false}
        if (d.param2 === -1) {return false}
        if (!requirementMet(s, d.param2, d.value2)) {return false}
    }

    for (let stat = 0; stat < 7; stat++) {
        const need = d.stats[stat]
        const have = s.stat(stat)
        if (need < 0 ? have >= -need : have < need) {return false}
    }
    return true
}
